/**
 * Compile-time TypeScript from checked-in OpenAPI family artifacts (#246).
 *
 * Types only. This script does not emit fetch clients, TanStack Query hooks,
 * mutations, cache helpers, or runtime validators. Each family is its own
 * module so a later combined /api/openapi.json (#45) can replace the inputs
 * without inventing that document here.
 *
 * Offline: reads docs/api/*.json. Does not start PRKS.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { COMMENT_HEADER, astToString } from "openapi-typescript";

const appRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = join(appRoot, "..");
const manifestPath = join(appRoot, "scripts/openapi-type-families.json");

const OPTIONS = {
  alphabetize: true,
  rootTypes: true,
  rootTypesNoSchemaPrefix: true,
  rootTypesKeepCasing: true,
  silent: true,
};

const PRKS_HEADER = `/**
 * Compile-time transport types for one PRKS OpenAPI family (#246).
 * Generated by frontend-app/scripts/generate-openapi-types.mjs.
 * Do not edit. This file is not a client, query layer, or runtime validator.
 */

`;

const BANNED = [
  "useQuery",
  "useMutation",
  "prksApiRequest",
  "fetch(",
  "axios",
  '@tanstack/',
];

function loadFamilies() {
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  if (!Array.isArray(manifest.families) || manifest.families.length === 0) {
    throw new Error("openapi-type-families.json has no families");
  }
  return manifest.families;
}

function assertFamilyPaths(family) {
  if (!family.artifact.startsWith("docs/api/") || !family.artifact.endsWith(".json")) {
    throw new Error(`${family.name}: artifact must be a docs/api/*.json file`);
  }
  const outputRel = family.output.replaceAll("\\", "/");
  if (!outputRel.startsWith("frontend-app/src/api/generated/") || !outputRel.endsWith(".ts")) {
    throw new Error(`${family.name}: output must be frontend-app/src/api/generated/*.ts`);
  }
}

async function renderFamily(family) {
  assertFamilyPaths(family);
  const artifactPath = resolve(repoRoot, family.artifact);
  const ast = await openapiTS(pathToFileURL(artifactPath), OPTIONS);
  const text = PRKS_HEADER + COMMENT_HEADER + astToString(ast);
  if (!text.endsWith("\n")) {
    return `${text}\n`;
  }
  return text;
}

function assertTypesOnly(family, text) {
  for (const token of BANNED) {
    if (text.includes(token)) {
      throw new Error(`${family.output} contains banned runtime token ${token}`);
    }
  }
}

export async function generateOpenApiTypes({ check = false } = {}) {
  const mismatches = [];
  for (const family of loadFamilies()) {
    const outputPath = resolve(repoRoot, family.output);
    const first = await renderFamily(family);
    const second = await renderFamily(family);
    assertTypesOnly(family, first);
    if (first !== second) {
      mismatches.push(`${family.output} (generation is not deterministic)`);
      continue;
    }
    if (check) {
      let current = "";
      try {
        current = readFileSync(outputPath, "utf8");
      } catch {
        mismatches.push(`${family.output} (missing)`);
        continue;
      }
      if (current !== first) mismatches.push(relative(repoRoot, outputPath));
      continue;
    }
    mkdirSync(dirname(outputPath), { recursive: true });
    writeFileSync(outputPath, first);
  }
  if (mismatches.length) {
    console.error("OpenAPI TypeScript types are stale:");
    for (const item of mismatches) console.error(`  ${item}`);
    console.error("Regenerate with: npm run openapi:types --prefix frontend-app");
    process.exitCode = 1;
    return false;
  }
  return true;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  await generateOpenApiTypes({ check: process.argv.includes("--check") });
}
